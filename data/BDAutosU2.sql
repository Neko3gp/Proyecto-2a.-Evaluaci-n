DROP TABLE Car_Details CASCADE CONSTRAINTS;
DROP TABLE Car_Names CASCADE CONSTRAINTS;
DROP TABLE Model_Details CASCADE CONSTRAINTS;
DROP TABLE Car_Makers CASCADE CONSTRAINTS;
DROP TABLE Countries CASCADE CONSTRAINTS;
DROP TABLE Continents;

CREATE TABLE Continents 
( 
    ContID NUMBER(5), 
    Continent VARCHAR2(15), 
    CONSTRAINT continent_id_pk PRIMARY KEY(ContID) 
);

CREATE TABLE Countries 
( 
    CountryID NUMBER(5), 
    CountryName VARCHAR2(20), 
    ContID NUMBER(5), 
    CONSTRAINT country_continent_id_fk FOREIGN KEY(ContID) REFERENCES Continents(ContID), 
    CONSTRAINT country_id_pk PRIMARY KEY(CountryID) 
);

CREATE TABLE Car_Makers 
( 
    IDMaker NUMBER(5), 
    Maker VARCHAR2(15), 
    FullName VARCHAR2(25), 
    CountryID NUMBER(5), 
    CONSTRAINT car_maker_country_id_fk FOREIGN KEY(CountryID) REFERENCES Countries(CountryID), 
    CONSTRAINT car_maker_id PRIMARY KEY(IDMaker) 
);

CREATE TABLE Model_Details 
( 
    ModelID NUMBER(5), 
    IDMaker NUMBER(5), 
    Model VARCHAR2(25), 
    CONSTRAINT model_unique UNIQUE(Model), 
    CONSTRAINT model_details_id_pk PRIMARY KEY(ModelID), 
    CONSTRAINT model_maker_fk FOREIGN KEY(IDMaker) REFERENCES Car_Makers(IDMaker) 
);

CREATE TABLE Car_Names 
( 
    IDCar NUMBER(5), 
    ModelID NUMBER(5), 
    Descr VARCHAR2(40), 
    CONSTRAINT car_names_id_pk PRIMARY KEY(IDCar), 
    CONSTRAINT car_names_model_fk FOREIGN KEY(ModelID) REFERENCES Model_Details(ModelID) 
);

CREATE TABLE Car_Details 
( 
    IDCar NUMBER(5), 
    mpg NUMBER(5,2), 
    cylinders NUMBER(5), 
    edispl NUMBER(10), 
    horsepower NUMBER(10), 
    weight NUMBER(10), 
    accel NUMBER(10,2), 
    year NUMBER(10), 
    CONSTRAINT car_details_id_pk PRIMARY KEY(IDCar), 
    CONSTRAINT car_details_id_fk FOREIGN KEY(IDCar) REFERENCES Car_Names(IDCar) 
);

